// Package matrix is the provider-extension capability matrix: for every
// maintained adapter and every provider-dependent verb, whether the
// adapter declares it, which test backs the row, where that test ran it
// and how mature the adapter says it is.
//
// The declarations and the maturity come from the adapters' own
// descriptors; the tests come from the explicit evidence map in this
// package. The package's test fails a row that cites a test that does
// not exist, a row that claims a recording its tests do not back, and a
// declared verb with no entry, so the published table cannot say more
// than the tests do. Maturity is the adapter author's word on how far the
// adapter is proven and is kept apart from what it declares.
package matrix

import (
	"errors"
	"fmt"
	"sort"
	"strings"

	"hop.top/heo/internal/adapters"
	"hop.top/uma/model"
)

// Row is one adapter and one provider-dependent verb.
type Row struct {
	Adapter model.TypeKey
	Verb    string
	// Declared is whether the adapter's descriptor enables the verb.
	Declared bool
	// Maturity is the descriptor's.
	Maturity string
	// Tests back the row. A declared verb cites the evidence map's entry
	// (none when nothing tests it); an undeclared one the tests of the
	// refusal every adapter meets for a verb it does not declare.
	// TestDeclaredVerbsPerAdapter pins the declared column of every row.
	Tests []TestRef
	// Against is where the behavior was exercised; for an undeclared
	// verb, where the refusal was.
	Against Kind
	// HasEvidence is whether the evidence map has an entry for the row.
	HasEvidence bool
}

// Rows returns a row for every adapter of r, in registration order, and
// every provider-dependent verb, in documentation order.
func Rows(r *adapters.Registry) []Row {
	var out []Row
	for _, typ := range r.Types() {
		a, _ := r.Lookup(typ)
		d := a.Factory.Describe()
		enabled := map[string]bool{}
		for _, v := range adapters.VerbsOf(a) {
			enabled[v] = true
		}
		for _, v := range adapters.ProviderVerbs() {
			row := Row{Adapter: typ, Verb: v.Name, Declared: enabled[v.Name], Maturity: d.Maturity, Against: None}
			switch e, ok := evidence[key(typ, v.Name)]; {
			case row.Declared && ok:
				row.HasEvidence = true
				row.Against = e.Against
				row.Tests = append([]TestRef{}, e.Tests...)
			case !row.Declared:
				// Refused before any write: the gate every undeclared verb
				// meets, on heo's fake provider.
				row.Against = Fake
				row.Tests = behavior(gateOf(v.Name)...)
			}
			out = append(out, row)
		}
	}
	return out
}

// gateOf is the tests of the refusal of verb.
func gateOf(verb string) []string {
	for _, g := range gates {
		if g.Verb == verb {
			return g.Tests
		}
	}
	return nil
}

// EvidenceKeys lists the adapter and verb of every evidence entry, as
// "adapter / verb".
func EvidenceKeys() []string {
	out := make([]string, 0, len(evidence))
	for k := range evidence {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// CitedTests lists, sorted and once, every test the matrix names.
func CitedTests(r *adapters.Registry) []string {
	seen := map[string]bool{DeclarationTest: true}
	for _, e := range evidence {
		for _, t := range e.Tests {
			seen[t.Name] = true
		}
	}
	for _, g := range gates {
		for _, t := range g.Tests {
			seen[t] = true
		}
	}
	for _, typ := range r.Types() {
		for _, t := range statuses[typ].Tests {
			seen[t.Name] = true
		}
	}
	out := make([]string, 0, len(seen))
	for n := range seen {
		out = append(out, n)
	}
	sort.Strings(out)
	return out
}

// gridColumns is how many verbs a grid of declared verbs holds.
const gridColumns = 8

// Markers delimit the generated block in docs/manual/provider-matrix.md.
const (
	Begin = "<!-- matrix:begin (generated by `make docs-gen`; do not edit) -->"
	End   = "<!-- matrix:end -->"
)

// Splice returns doc with the block between the markers replaced by
// block.
func Splice(doc, block string) (string, error) {
	i, j := strings.Index(doc, Begin), strings.Index(doc, End)
	if i < 0 || j < 0 || j < i {
		return "", errors.New("matrix: the document lacks its begin and end markers, in that order")
	}
	return doc[:i+len(Begin)] + "\n" + block + doc[j:], nil
}

func cite(ts []TestRef) string {
	if len(ts) == 0 {
		return "none"
	}
	parts := make([]string, 0, len(ts))
	for _, t := range ts {
		s := "`" + t.Name + "`"
		if !t.Behavior {
			s += " (check only)"
		}
		parts = append(parts, s)
	}
	return strings.Join(parts, ", ")
}

func yesNo(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

// Render returns the generated block: the declaration grid, one evidence
// row per adapter and verb, the refusal gate per verb and the recording
// status per adapter.
func Render(r *adapters.Registry) string {
	rows := Rows(r)
	verbs := adapters.ProviderVerbs()
	var b strings.Builder

	// The grid is cut into groups of verbs, each with the adapter column,
	// so a row stays readable as verbs are added.
	for from := 0; from < len(verbs); from += gridColumns {
		to := min(from+gridColumns, len(verbs))
		title := "### Declared verbs\n\n"
		if from > 0 {
			title = "\n### Declared verbs, continued\n\n"
		}
		b.WriteString(title + "| Adapter |")
		sep := "| --- |"
		for _, v := range verbs[from:to] {
			b.WriteString(" " + v.Name + " |")
			sep += " --- |"
		}
		last := to == len(verbs)
		if last {
			b.WriteString(" Maturity |")
			sep += " --- |"
		}
		b.WriteString("\n" + sep + "\n")
		for _, typ := range r.Types() {
			fmt.Fprintf(&b, "| `%s` |", typ)
			mat := ""
			for _, row := range rows {
				if row.Adapter != typ {
					continue
				}
				mat = row.Maturity
				for _, v := range verbs[from:to] {
					if row.Verb == v.Name {
						fmt.Fprintf(&b, " %s |", yesNo(row.Declared))
					}
				}
			}
			if last {
				fmt.Fprintf(&b, " %s |", mat)
			}
			b.WriteString("\n")
		}
	}

	b.WriteString("\n### Evidence per adapter and verb\n\n")
	b.WriteString("| Adapter | Verb | Declared | Tested by | Recorded against | Maturity |\n| --- | --- | --- | --- | --- | --- |\n")
	for _, row := range rows {
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n", row.Adapter, row.Verb, yesNo(row.Declared), cite(row.Tests), row.Against, row.Maturity)
	}

	b.WriteString("\n### Recording status per adapter\n\n")
	for _, typ := range r.Types() {
		s, ok := statuses[typ]
		if !ok {
			fmt.Fprintf(&b, "- `%s`, recorded against **%s**: no status recorded.\n", typ, None)
			continue
		}
		b.WriteString(wrapItem(fmt.Sprintf("`%s`, recorded against **%s**: %s. A recording needs: %s. Tested by: %s.",
			typ, s.Against, strings.TrimSuffix(s.Summary, "."), strings.TrimSuffix(s.Needs, "."), cite(s.Tests))))
	}
	return b.String()
}

// wrapItem is a bullet of text, wrapped at 100 columns with continuation
// lines indented under it.
func wrapItem(text string) string {
	const width = 100
	var b strings.Builder
	line := "-"
	for _, w := range strings.Fields(text) {
		if len([]rune(line))+1+len([]rune(w)) > width {
			b.WriteString(line + "\n")
			line = " "
		}
		line += " " + w
	}
	b.WriteString(line + "\n")
	return b.String()
}
