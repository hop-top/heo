package refdoc

import (
	"fmt"
	"sort"
	"strings"
)

// Example is one literal invocation of a verb.
type Example struct {
	Title   string
	Command string
}

// Leaf is one runnable verb, as `heo spec` and the command tree
// describe it. Path is the words below the root, space separated.
type Leaf struct {
	Path        string
	Short       string
	SideEffect  string
	Idempotent  string
	DryRun      bool
	Daemon      bool
	SelfHosting bool
	// Withheld lists the surfaces the command opts out of.
	Withheld   []string
	Capability string
	Examples   []Example
}

// Header opens every generated file.
const header = "<!-- Generated by `make docs-gen` from `heo spec` and the command tree. Do not edit. -->"

func (l Leaf) group() string {
	if i := strings.IndexByte(l.Path, ' '); i > 0 {
		return l.Path[:i]
	}
	return l.Path
}

func (l Leaf) destructive() bool { return strings.HasPrefix(l.SideEffect, "destructive") }

// limit says where a served surface may not run the verb.
func (l Leaf) limit(m Meta) string {
	switch {
	case m.Limit != "":
		return m.Limit
	case l.SelfHosting:
		return "terminal only"
	case l.destructive() && l.Daemon:
		return "socket only"
	case l.destructive():
		return "local only"
	case len(l.Withheld) > 0:
		return "not on REST, gRPC or MCP"
	}
	return "-"
}

func (l Leaf) runs() string {
	if l.Daemon {
		return "daemon"
	}
	return "local"
}

// effect is the side-effect tier with the idempotency and dry-run
// facts, in one cell.
func (l Leaf) effect() string {
	s := fmt.Sprintf("`%s`, idempotent %s", l.SideEffect, l.Idempotent)
	if l.DryRun {
		s += ", dry-run"
	}
	return s
}

func (l Leaf) does() string {
	s := l.Short
	if l.Capability != "" {
		s += " (needs `" + l.Capability + "`)"
	}
	return s
}

// groups returns the leaves grouped by first word, groups and leaves
// sorted.
func groups(leaves []Leaf) ([]string, map[string][]Leaf) {
	by := map[string][]Leaf{}
	for _, l := range leaves {
		by[l.group()] = append(by[l.group()], l)
	}
	names := make([]string, 0, len(by))
	for g := range by {
		sort.Slice(by[g], func(i, j int) bool { return by[g][i].Path < by[g][j].Path })
		names = append(names, g)
	}
	sort.Strings(names)
	return names, by
}

func cell(s string) string { return strings.ReplaceAll(s, "|", `\|`) }

// wrap breaks s at width on spaces.
func wrap(s string, width int) string {
	var out []string
	line := ""
	for _, w := range strings.Fields(s) {
		if line != "" && len(line)+1+len(w) > width {
			out = append(out, line)
			line = w
			continue
		}
		if line != "" {
			line += " "
		}
		line += w
	}
	if line != "" {
		out = append(out, line)
	}
	return strings.Join(out, "\n")
}

type builder struct{ strings.Builder }

func (b *builder) line(s string)            { b.WriteString(s + "\n") }
func (b *builder) para(s string)            { b.line(wrap(s, 100)); b.line("") }
func (b *builder) linef(f string, a ...any) { b.line(fmt.Sprintf(f, a...)) }
func (b *builder) row(cols ...string)       { b.line("| " + strings.Join(cols, " | ") + " |") }
func (b *builder) head(cols ...string)      { b.row(cols...); b.row(dashes(len(cols))...) }
func (b *builder) fence(info string, body []string) {
	b.line("```" + info)
	for _, s := range body {
		b.line(s)
	}
	b.line("```")
	b.line("")
}

func dashes(n int) []string {
	out := make([]string, n)
	for i := range out {
		out[i] = "---"
	}
	return out
}

func quote(path string) string { return "`heo " + path + "`" }

// Reference renders the command reference: every verb with its side
// effect, who may run it and which uma call backs it, the examples the
// tree carries, and the grammar's gaps.
func Reference(leaves []Leaf) string {
	var b builder
	b.line(header)
	b.line("")
	b.line("# Command reference")
	b.line("")
	b.para("Every verb of this build of heo, generated from its capability manifest (`heo spec`) " +
		"and its command tree. For what a verb does in prose, see [commands](commands.md); " +
		"for the verbs the grammar names and this build lacks, see " +
		"[Grammar coverage](#grammar-coverage).")

	b.line("## How to read the tables")
	b.line("")
	b.head("Column", "Meaning")
	b.row("Effect", "kit's `kit/side-effect` tier, then `kit/idempotent` (`yes`, `no`, `conditional`: replays under an `--idempotency-key`), then `dry-run` when `--dry-run` is honoured")
	b.row("Runs in", "`daemon`: executes in the profile's daemon, exit 70 with none running. `local`: executes in the invoking process")
	b.row("Roles", "who may run it: the authorization roles (see [authorization](authorization.md)), `host user` for the daemon's own lifecycle and store, `none (offline)` for a verb that needs no daemon, store or role")
	b.row("uma", "the uma call behind the verb; `none` says what backs it instead")
	b.row("Limit", "where a served surface refuses it: `terminal only` never served, `socket only` destructive or management, `not on REST, gRPC or MCP` streams. `-`: heo declares no limit; discovery on a running daemon is the authority")
	b.line("")

	names, by := groups(leaves)
	b.line("## Verbs")
	b.line("")
	for _, g := range names {
		b.linef("### %s", g)
		b.line("")
		b.head("Verb", "Does", "Effect", "Runs in", "Roles", "uma", "Limit")
		for _, l := range by[g] {
			m, _ := Lookup(l.Path)
			b.row(quote(l.Path), cell(l.does()), l.effect(), l.runs(), cell(m.Roles), cell(m.UMA), l.limit(m))
		}
		b.line("")
		var ex []string
		for _, l := range by[g] {
			for _, e := range l.Examples {
				ex = append(ex, "# "+e.Title, e.Command)
			}
		}
		if len(ex) > 0 {
			b.fence("sh", ex)
		}
	}

	b.line("## Grammar coverage")
	b.line("")
	b.para("Every resource and verb of the grammar is in the tables above, or here with the reason " +
		"it is not. A row leaves this table when its verb ships; a test fails while a verb is in " +
		"both places, and while a verb is in neither.")
	b.head("Verb", "Status", "Why")
	for _, g := range Gaps {
		v := g.Verb
		if !strings.HasPrefix(v, "(") {
			v = quote(v)
		}
		b.row(v, g.Status, cell(g.Why))
	}
	b.line("")
	b.para("Statuses: `deferred` waits on a uma capability that does not exist yet; " +
		"`not built` is heo-side work not done; `cut` was decided against; " +
		"`folded` is served by another verb.")
	return b.String()
}

// CheatsheetAgent renders the cheatsheet for a program or an LLM that
// calls heo: the rules, then every verb in one dense table.
func CheatsheetAgent(leaves []Leaf) string {
	var b builder
	b.line(header)
	b.line("")
	b.line("# heo cheatsheet: agents")
	b.line("")
	b.para("For a program or an LLM calling heo. Prefer the machine-readable manifest to this page: " +
		"it is the same data. The prose behind each verb is in [commands](manual/commands.md); " +
		"the roles are in [authorization](manual/authorization.md).")

	b.line("## Discover")
	b.line("")
	b.fence("sh", []string{
		"heo spec --format json                 # every verb: side effect, flags, examples, next steps",
		"heo spec --version                     # the manifest schema version alone",
		"heo spec coverage --min 100            # fails while a verb lacks a side-effect tier",
		"heo adapter list --format json         # what each adapter in this build can do",
		"heo channel get <channel> --format json   # which provider verbs a channel supports",
	})
	b.para("Over REST the same list is `GET /v1/commands`; over MCP each verb is one tool, named by " +
		"its path joined with dots (`conversation.list`). Both list only what you may call.")

	b.line("## Rules")
	b.line("")
	rules := []string{
		"Pass `--format json`. Parse stdout; errors are a JSON envelope on stderr with `code`, " +
			"`message`, `suggested_fix` and `transience`.",
		"IDs are record IDs, as the listing printed them (`conv_123`, `msg_123`, `op_123`). " +
			"Never build one.",
		"Preview before you write: every verb marked `dry-run` takes `--dry-run`, which prints the " +
			"exact effect and writes nothing.",
		"Writes are uma operations. Pass `--idempotency-key` (or keep the one heo printed) so a " +
			"retry replays instead of repeating. A write that returns `queued` is accepted, " +
			"not delivered: follow it with `heo delivery get <operation>`.",
		"Exit 70: no daemon is running. Do not retry; a human runs `heo service start`.",
		"Exit 4 is a conflict (stale `--revision`, state moved): re-read, then decide. " +
			"Exit 6 is transient: back off and retry. Exit 8 is `OUTCOME_UNKNOWN`: the provider " +
			"may have acted; `heo delivery reconcile <operation>`, never a blind resend.",
		"Exit 5 is a refusal: your role does not allow it, or a destructive verb has no " +
			"`--confirm=yes`. Do not retry unchanged.",
		"Destructive verbs (`contact merge`, `message delete`, `storage restore`) are refused " +
			"over REST, gRPC and MCP; the control socket runs them with `--confirm=yes`.",
		"A `plugin:` actor's write may be held (state `held`): only a person runs `heo operation " +
			"held approve|edit|reject`; a plugin is refused, exit 5. Over MCP `held show|approve|edit|reject` " +
			"name their operation with `--operation`.",
		"Streams (`event watch`, `task watch`, `operation watch`) are for a terminal or the " +
			"socket: poll `event list --cursor` from a served surface.",
		"A hook plugin is any executable: an envelope in on stdin, a result of operations out on " +
			"stdout. Try one with `heo hook test <plugin> --event <id>` before enabling it; see " +
			"[write a plugin](manual/hooks.md#write-a-plugin-in-any-language).",
	}
	for _, r := range rules {
		b.line(strings.ReplaceAll(wrap("- "+r, 98), "\n", "\n  "))
	}
	b.line("")

	b.line("## Exit codes")
	b.line("")
	b.head("Exit", "Meaning", "Retry")
	b.row("0", "success", "-")
	b.row("1", "unclassified failure, or a schema newer than this binary", "no, report")
	b.row("2", "usage error, validation, or `UNSUPPORTED` by the channel's adapter", "no, fix the call")
	b.row("3", "not found", "no")
	b.row("4", "conflict: stale revision, owned store, daemon already running", "re-read first")
	b.row("5", "refused: no role, or destructive without `--confirm=yes`", "no")
	b.row("6", "transient", "yes, with backoff")
	b.row("8", "`OUTCOME_UNKNOWN`: the provider may have acted", "reconcile, do not resend")
	b.row("70", "no daemon is running", "no, a human starts it")
	b.line("")

	b.line("## Verbs")
	b.line("")
	b.head("Verb", "Effect", "Runs in", "Roles", "uma", "Limit")
	names, by := groups(leaves)
	for _, g := range names {
		for _, l := range by[g] {
			m, _ := Lookup(l.Path)
			b.row(quote(l.Path), l.effect(), l.runs(), cell(m.Roles), cell(m.UMA), l.limit(m))
		}
	}
	b.line("")
	return b.String()
}

// CheatsheetHuman renders the cheatsheet for a person at a terminal:
// the commands of a first hour, then every verb with one example.
func CheatsheetHuman(leaves []Leaf) string {
	var b builder
	b.line(header)
	b.line("")
	b.line("# heo cheatsheet: people")
	b.line("")
	b.para("For a person at a terminal. Start with [getting started](manual/getting-started.md); " +
		"every verb is explained in [commands](manual/commands.md), and the full table of effects " +
		"and roles is the [command reference](manual/command-reference.md).")

	b.line("## First hour")
	b.line("")
	b.fence("sh", []string{
		"heo service setup api              # enable REST on loopback and mint the surface token",
		"heo service start                  # run the daemon in the foreground",
		"heo service status                 # in another terminal: is everything ready",
		"heo channel list                   # configured connections",
		"heo conversation list --status open",
		"heo message list --conversation conv_123",
		"heo message reply conv_123 --text \"Thanks, we're on it.\" --dry-run",
		"heo delivery get op_123            # did the reply leave",
		"heo service stop                   # drain and exit",
	})

	b.line("## Reading the tables")
	b.line("")
	b.para("Effect: `read` changes nothing; `write` changes uma or the profile; `write-shared` also " +
		"reaches a provider or the daemon; `destructive-*` cannot be undone and asks to be " +
		"confirmed. Roles: `operator` configures, `desk` works conversations, `viewer` reads, " +
		"`external` reads public content only. Every write takes `--dry-run`, `--idempotency-key` " +
		"and, where it is optimistic, `--revision`.")
	b.para("To react to events with your own program in any language, see " +
		"[write a plugin](manual/hooks.md#write-a-plugin-in-any-language); `heo hook` runs, tests " +
		"and replays plugins.")

	names, by := groups(leaves)
	b.line("## Every verb")
	b.line("")
	for _, g := range names {
		b.linef("### %s", g)
		b.line("")
		b.head("Verb", "Does", "Effect", "Roles", "Example")
		for _, l := range by[g] {
			m, _ := Lookup(l.Path)
			ex := "-"
			if len(l.Examples) > 0 {
				ex = "`" + cell(l.Examples[0].Command) + "`"
			}
			b.row(quote(l.Path), cell(l.does()), "`"+l.SideEffect+"`", cell(m.Roles), ex)
		}
		b.line("")
	}
	return b.String()
}
